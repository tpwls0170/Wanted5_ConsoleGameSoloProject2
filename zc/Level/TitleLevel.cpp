void TitleLevel::Tick(float deltaTime)
{
    Level::Tick(deltaTime);
	DebugDraw();

	if (Input::Get().GetKeyDown(VK_ESCAPE))
	{
		Engine::Get().Quit();
	}

	if (Input::Get().GetKeyDown(VK_RETURN))
	{
		GameLevelManager& gameLevelManager = dynamic_cast<GameLevelManager&>(Engine::Get());
		gameLevelManager.ToggleMenu(State::TitleMenu, State::GamePlay);
	}
}

void TitleLevel::DebugDraw()
{
    const int screenWidth =
        static_cast<int>(Engine::Get().GetWidth());

    const int screenHeight =
        static_cast<int>(Engine::Get().GetHeight());

    const int titleHeight =
        static_cast<int>(title.size());

    // 타이틀 전체의 세로 시작 위치
    const int startY =
        ((screenHeight - titleHeight) / 2) + 3;

    for (int y = 0; y < titleHeight; ++y)
    {
        const int titleWidth =
            static_cast<int>(title[y].size());

        // 각 줄을 가로 중앙 정렬
        const int startX =
            (screenWidth - titleWidth) / 2;

        Renderer::Get().Submit(
            title[y],
            Vector2(startX, startY + y),
            Craft::Color::Green
        );
    }
}
